// Publishes docs/API.md at login.2earl.com/docs/api: converts it to HTML and writes
// src/api-docs.generated.ts. The repository is private; customers read the page instead.
//
//   node scripts/api-docs.mjs          rewrite src/api-docs.generated.ts
//   node scripts/api-docs.mjs --check  fail if it is out of date (CI)
//
// The converter covers what API.md uses: headings, paragraphs, lists, tables, fenced code,
// `code`, **bold**, *emphasis*, [links](…) and <autolinks>. Anything else is escaped as text.
import { readFile, writeFile } from 'node:fs/promises';

const OUT = 'src/api-docs.generated.ts';

const escape = (text) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function inline(text) {
  const parts = text.split(/(`[^`]+`)/);
  return parts
    .map((part) => {
      if (part.startsWith('`') && part.endsWith('`') && part.length > 1) {
        return `<code>${escape(part.slice(1, -1))}</code>`;
      }
      return escape(part)
        .replace(/&lt;(https:\/\/[^\s&]+)&gt;/g, '<a href="$1">$1</a>')
        .replace(/\[([^\]]+)\]\((https:\/\/[^)\s]+)\)/g, '<a href="$2">$1</a>')
        .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
        .replace(/\*([^*]+)\*/g, '<em>$1</em>');
    })
    .join('');
}

const slug = (text) =>
  text
    .toLowerCase()
    .replace(/`/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

export function toHtml(markdown) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (line.trim() === '') {
      i += 1;
    } else if (line.startsWith('```')) {
      const body = [];
      i += 1;
      while (i < lines.length && !lines[i].startsWith('```')) body.push(lines[i++]);
      i += 1;
      out.push(`<pre><code>${escape(body.join('\n'))}</code></pre>`);
    } else if (/^#{1,3} /.test(line)) {
      const level = line.indexOf(' ');
      const text = line.slice(level + 1);
      out.push(`<h${level} id="${slug(text)}">${inline(text)}</h${level}>`);
      i += 1;
    } else if (line.startsWith('|')) {
      const rows = [];
      while (i < lines.length && lines[i].startsWith('|')) rows.push(lines[i++]);
      const cells = (row) =>
        row
          .slice(1, row.endsWith('|') ? -1 : undefined)
          .split('|')
          .map((cell) => cell.trim());
      const [head, , ...body] = rows;
      out.push(
        '<div class="table-wrap"><table class="log"><thead><tr>' +
          cells(head)
            .map((c) => `<th>${inline(c)}</th>`)
            .join('') +
          '</tr></thead><tbody>' +
          body
            .map(
              (row) =>
                '<tr>' +
                cells(row)
                  .map((c) => `<td>${inline(c)}</td>`)
                  .join('') +
                '</tr>',
            )
            .join('') +
          '</tbody></table></div>',
      );
    } else if (line.startsWith('- ')) {
      const items = [];
      while (i < lines.length && (lines[i].startsWith('- ') || lines[i].startsWith('  '))) {
        if (lines[i].startsWith('- ')) items.push(lines[i].slice(2));
        else items[items.length - 1] += ` ${lines[i].trim()}`;
        i += 1;
      }
      out.push(`<ul>${items.map((item) => `<li>${inline(item)}</li>`).join('')}</ul>`);
    } else {
      const text = [];
      while (i < lines.length && lines[i].trim() !== '' && !/^(#{1,3} |```|\||- )/.test(lines[i])) {
        text.push(lines[i++].trim());
      }
      out.push(`<p>${inline(text.join(' '))}</p>`);
    }
  }
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const markdown = await readFile('docs/API.md', 'utf8');
  // The note about where the page is published is for readers of the file, not of the page.
  const body = toHtml(markdown.replace(/^This page is published at .*\n\n/m, ''));
  const next =
    '// Generated by scripts/api-docs.mjs from docs/API.md. Do not edit.\n' +
    `export const API_DOCS_HTML = ${JSON.stringify(body)};\n`;
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current !== next) {
    if (process.argv.includes('--check')) {
      console.error(`${OUT} is out of date: run node scripts/api-docs.mjs`);
      process.exit(1);
    }
    await writeFile(OUT, next);
  }
}
